SELECT *
FROM GOLD.TOP_PRODUCTS
ORDER BY TOTAL_SALES DESC
LIMIT 10;

SELECT
    COUNT(*) AS NUMBER_OF_PRODUCTS,
    SUM(TOTAL_SALES) AS TOTAL_SALES,
    SUM(TOTAL_QUANTITY_SOLD) AS TOTAL_QUANTITY
FROM GOLD.TOP_PRODUCTS;


