use role role_data_engineer; 
use warehouse wh_commercial_analytics;
use database commercial_analytics; 
use schema commercial_analytics.gold ; 

show tables in schema commercial_analytics.gold ; 

-- tester sales by country 
SELECT *
FROM GOLD.SALES_BY_COUNTRY
ORDER BY COUNTRY;

SELECT COUNT(*) AS NUMBER_OF_COUNTRIES
FROM GOLD.SALES_BY_COUNTRY;

SELECT
    SUM(TOTAL_SALES) AS GOLD_TOTAL_SALES,
    SUM(NUMBER_OF_ORDERS) AS GOLD_NUMBER_OF_ORDERS,
    SUM(TOTAL_QUANTITY_SOLD) AS GOLD_TOTAL_QUANTITY
FROM GOLD.SALES_BY_COUNTRY;

-- tester sales by month
SELECT *
FROM GOLD.SALES_BY_MONTH
ORDER BY SALE_MONTH;

SELECT
    MIN(SALE_MONTH) AS FIRST_MONTH,
    MAX(SALE_MONTH) AS LAST_MONTH,
    COUNT(*) AS NUMBER_OF_MONTHS
FROM GOLD.SALES_BY_MONTH;

SELECT
    SUM(TOTAL_SALES) AS TOTAL_SALES,
    SUM(TOTAL_QUANTITY_SOLD) AS TOTAL_QUANTITY
FROM GOLD.SALES_BY_MONTH;

